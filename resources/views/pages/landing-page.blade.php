            /* Split de palabras */
            function splitWords(el) {
                const makeWrap = () => {
                    const w = document.createElement('span');
                    w.className = 'w';
                    w.style.cssText = 'display:inline-block;overflow:hidden;vertical-align:top;padding-bottom:0.14em;margin-bottom:-0.14em;';
                    const i = document.createElement('span');
                    i.className = 'wi';
                    i.style.cssText = 'display:inline-block;will-change:transform;';
                    w.appendChild(i);
                    return { w, i };
                };

                const walk = (node) => {
                    Array.from(node.childNodes).forEach((ch) => {
                        if (ch.nodeType === 3) {
                            const frag = document.createDocumentFragment();
                            ch.textContent.split(/(\s+)/).forEach((p) => {
                                if (!p) return;
                                if (/^\s+$/.test(p)) {
                                    frag.appendChild(document.createTextNode(' '));
                                } else {
                                    const { w, i } = makeWrap();
                                    i.textContent = p;
                                    frag.appendChild(w);
                                }
                            });
                            ch.replaceWith(frag);
                        } else if (ch.nodeType === 1) {
                            if (ch.classList.contains('highlight')) {
                                // NO se parte por dentro: se anima el bloque entero
                                const { w, i } = makeWrap();
                                ch.replaceWith(w);
                                i.appendChild(ch);
                            } else {
                                walk(ch);
                            }
                        }
                    });
                };
                walk(el);
                el.classList.add('is-split');
                return $$('.wi', el);
            }

