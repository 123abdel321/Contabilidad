            function updateActiveNav() {
                if (!navLinks.length) return;
                const sections = navLinks
                    .map((l) => l.getAttribute('href'))
                    .filter((h) => h && h.startsWith('#') && h.length > 1)
                    .map((id) => document.querySelector(id))
                    .filter(Boolean);
